/** Least-trustworthy provenance among a set, for a combined badge. */
export function weakestProvenance(list: Provenance[]): Provenance {
  const order: Provenance[] = ["measured", "reconstructed", "ai_generated", "illustrative"];
  return list.reduce<Provenance>((acc, p) => (order.indexOf(p) > order.indexOf(acc) ? p : acc), "measured");
}
